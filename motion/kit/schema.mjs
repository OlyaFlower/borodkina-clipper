// Builds motion/kit/scene.schema.json from the block modules, so the schema and the blocks cannot drift:
//   node motion/kit/schema.mjs > motion/kit/scene.schema.json
// The kit tests check that the committed file equals this output.

import { pathToFileURL } from 'node:url';
import { CAMERAS, KIT_VERSION, RHYTHMS } from './lib/loop.js';
import { CUSTOM_RE, INTENSITIES, KIT_BLOCKS, NAMED_COLOURS } from './lib/spec.js';

export async function kitBlocks() {
  const out = {};
  for (const name of KIT_BLOCKS) {
    out[name] = { ...(await import(new URL(`./blocks/${name}.js`, import.meta.url))).default, name };
  }
  return out;
}

function paramSchema(decl) {
  const about = decl.about ? { description: decl.about } : {};
  switch (decl.type) {
    case 'number':
      return { type: 'number', minimum: decl.min, maximum: decl.max, default: decl.default, ...about };
    case 'enum':
      return { enum: decl.values, default: decl.default, ...about };
    case 'boolean':
      return { type: 'boolean', default: decl.default, ...about };
    case 'colour':
      return {
        type: 'string',
        anyOf: [{ enum: NAMED_COLOURS }, { pattern: '^#[0-9a-fA-F]{6}$' }],
        default: decl.default,
        ...about,
      };
    default:
      throw new Error(`unknown parameter type ${decl.type}`);
  }
}

export function buildSchema(blocks) {
  const definitions = {
    timing: {
      type: 'object',
      additionalProperties: false,
      properties: {
        rhythm: { enum: RHYTHMS, description: 'primary: the beats; reactive: answers them; ambient: always on; wave: one slow swell' },
        delay: { type: 'number', minimum: -1, maximum: 1, description: 'shift of the beats for this block, s' },
      },
    },
  };
  const conditions = [];
  for (const [name, block] of Object.entries(blocks)) {
    definitions[`params-${name}`] = {
      type: 'object',
      additionalProperties: false,
      properties: Object.fromEntries(Object.entries(block.params).map(([k, d]) => [k, paramSchema(d)])),
    };
    conditions.push({
      if: { properties: { block: { const: name } } },
      then: { properties: { params: { $ref: `#/definitions/params-${name}` } } },
    });
  }
  definitions.entry = {
    type: 'object',
    required: ['block'],
    additionalProperties: false,
    properties: {
      block: {
        anyOf: [{ enum: Object.keys(blocks) }, { type: 'string', pattern: CUSTOM_RE.source }],
        description: 'a kit block, or custom/<name> for blocks/<name>.js next to the spec',
      },
      preset: { enum: INTENSITIES, description: 'intensity preset of the block (default subtle)' },
      params: { type: 'object', description: 'overrides of the preset' },
      timing: { $ref: '#/definitions/timing' },
    },
    allOf: conditions,
  };
  return {
    $schema: 'http://json-schema.org/draft-07/schema#',
    $id: 'https://github.com/OlyaFlower/borodkina-clipper/blob/develop/motion/kit/scene.schema.json',
    title: `Motion ${KIT_VERSION} scene spec`,
    description:
      'An 8 s seamless loop composed from kit blocks (motion/kit/API.md). The first block is the base (parallax or card-float); the others are applied in order. Generated by motion/kit/schema.mjs.',
    type: 'object',
    required: ['kit', 'blocks'],
    additionalProperties: false,
    properties: {
      $schema: { type: 'string' },
      kit: { const: KIT_VERSION },
      name: { type: 'string', pattern: '^[a-z][a-z0-9-]{0,39}$' },
      about: { type: 'string', maxLength: 400 },
      seed: { type: 'integer', minimum: 0, maximum: 4294967295 },
      beats: {
        type: 'array',
        maxItems: 3,
        items: { type: 'number', exclusiveMinimum: 0.5, exclusiveMaximum: 6.4 },
        description: 'beat times in seconds (loop-safe range 0.5..6.4)',
      },
      blocks: { type: 'array', minItems: 1, maxItems: 12, items: { $ref: '#/definitions/entry' } },
    },
    definitions,
    // Cameras are listed for readers; the parallax params carry the authoritative enum.
    $comment: `cameras: ${CAMERAS.join(', ')}`,
  };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.stdout.write(`${JSON.stringify(buildSchema(await kitBlocks()), null, 2)}\n`);
}
